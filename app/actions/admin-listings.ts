export type CreateDraftState = { error?: string; fieldErrors?: Record<string, string> } | undefined;

/** Creates a draft (the row must exist before photos can be uploaded) and opens it. */
export async function createDraft(_prev: CreateDraftState, formData: FormData): Promise<CreateDraftState> {
  const session = await requireUser();
  const parsed = newListingSchema.safeParse({
    category_id: formData.get("category_id"),
    title_en: formData.get("title_en"),
  });
  if (!parsed.success) return { fieldErrors: fieldErrors(parsed.error) };

  const { data, error } = await session.supabase
    .from("listings")
    .insert({
      ...parsed.data,
      slug: "", // generated by the listings_set_slug trigger
      status: "draft",
      created_by: session.userId,
    })
    .select("id")
    .single();
  if (error || !data) {
    console.error("createDraft failed", error?.code, error?.message);
    return { error: "Couldn't create the listing. Please try again." };
  }
  redirect(`/admin/listings/${data.id}`);
}

/** Saves the listing form. Called by auto-save and by the Save button. */
export async function saveListing(
  id: string,
  values: ListingFormValues,
  privateValues?: ListingPrivateValues,
): Promise<SaveResult> {
  const session = await getSession();
  if (!session) return { ok: false, error: "Your session has expired. Please sign in again." };
  if (!UUID_RE.test(id)) return { ok: false, error: "Unknown listing." };

  const listing = await getEditableListing(session, id);
  if (!listing) return { ok: false, error: "You can't edit this listing any more." };

  const parsed = listingFormSchema.safeParse(values);
  if (!parsed.success) {
    return { ok: false, error: "Please fix the highlighted fields.", fieldErrors: fieldErrors(parsed.error) };
  }

  const { data, error } = await session.supabase
    .from("listings")
    .update(parsed.data)
    .eq("id", id)
    .select("slug, status, title_en, year, make, model, location")
    .maybeSingle();
  if (error || !data) {
    console.error("saveListing failed", error?.code, error?.message);
    return { ok: false, error: error?.code === "23503" ? "Unknown category." : "Couldn't save. Please try again." };
  }

  // Alt text follows the listing (CLAUDE.md §8): `{year} {make} {model} {title} — {location}`.
  if (listingAlt(data) !== listingAlt(listing)) {
    await session.supabase.from("listing_images").update({ alt_text: listingAlt(data) }).eq("listing_id", id);
  }

  if (session.isOwner && privateValues) {
    const priv = listingPrivateSchema.safeParse(privateValues);
    if (!priv.success) {
      return { ok: false, error: "Please fix the highlighted fields.", fieldErrors: fieldErrors(priv.error) };
    }
    const { error: privError } = await session.supabase
      .from("listing_private")
      .upsert({ listing_id: id, ...priv.data });
    if (privError) {
      console.error("saveListing private failed", privError.code, privError.message);
      return { ok: false, error: "Saved the listing, but not the private notes." };
    }
  }

  if (isPublicStatus(data.status) || isPublicStatus(listing.status)) {
    expireListingCaches(listing.slug, data.slug);
  }
  return { ok: true, savedAt: new Date().toISOString(), slug: data.slug };
}

