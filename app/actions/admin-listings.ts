/**
 * Admin listing mutations. Every action re-checks the caller and runs through their
 * RLS-bound Supabase client, so a forged request still can't exceed the DB policies.
 */

export type ActionResult = { ok: true } | { ok: false; error: string };
export type SaveResult =
  | { ok: true; savedAt: string; slug: string }
  | { ok: false; error: string; fieldErrors?: Record<string, string> };

const NOT_ALLOWED: ActionResult = { ok: false, error: "You can't edit this listing any more." };

function fieldErrors(error: z.ZodError): Record<string, string> {
  const out: Record<string, string> = {};
  for (const issue of error.issues) {
    const key = String(issue.path[0] ?? "form");
    out[key] ??= issue.message;
  }
  return out;
}

