async function imageCount(session: Awaited<ReturnType<typeof requireUser>>, id: string): Promise<number> {
  const { count } = await session.supabase
    .from("listing_images")
    .select("id", { count: "exact", head: true })
    .eq("listing_id", id);
  return count ?? 0;
}

/** Staff: draft → pending (owner approval queue). */
export async function submitForReview(id: string): Promise<ActionResult> {
  const session = await requireUser();
  if (!UUID_RE.test(id)) return NOT_ALLOWED;
  const listing = await getEditableListing(session, id);
  if (!listing || listing.status !== "draft") return NOT_ALLOWED;
  if ((await imageCount(session, id)) === 0) return { ok: false, error: "Add at least one photo first." };

  const { error } = await session.supabase.from("listings").update({ status: "pending" }).eq("id", id);
  if (error) return { ok: false, error: "Couldn't submit. Please try again." };
  return { ok: true };
}

const statusSchema = z.enum(["draft", "pending", "available", "reserved", "sold", "archived"]);

/**
 * Owner: approve / reserve / sell / archive / reopen. DB triggers set published_at,
 * sold_at and the archive redirect (CLAUDE.md §3.5).
 */
export async function setListingStatus(id: string, status: ListingStatus): Promise<ActionResult> {
  const session = await requireOwner();
  const parsedStatus = statusSchema.safeParse(status);
  if (!UUID_RE.test(id) || !parsedStatus.success) return NOT_ALLOWED;

  const listing = await getEditableListing(session, id);
  if (!listing) return NOT_ALLOWED;
  if (isPublicStatus(parsedStatus.data) && (await imageCount(session, id)) === 0) {
    return { ok: false, error: "Add at least one photo before publishing." };
  }

  const patch: { status: ListingStatus; sold_at?: null } = { status: parsedStatus.data };
  if (parsedStatus.data !== "sold") patch.sold_at = null;

  const { error } = await session.supabase.from("listings").update(patch).eq("id", id);
  if (error) {
    console.error("setListingStatus failed", error.code, error.message);
    return { ok: false, error: "Couldn't change the status." };
  }
  expireListingCaches(listing.slug);
  return { ok: true };
}

/** Owner: delete for good. The DB trigger 301s the old URL to its category if it was ever public. */
export async function deleteListing(id: string): Promise<ActionResult> {
  const session = await requireOwner();
  if (!UUID_RE.test(id)) return NOT_ALLOWED;
  const listing = await getEditableListing(session, id);
  if (!listing) return NOT_ALLOWED;

  const { data: images } = await session.supabase
    .from("listing_images")
    .select("r2_key, thumb_key")
    .eq("listing_id", id);

  const { error } = await session.supabase.from("listings").delete().eq("id", id);
  if (error) {
    console.error("deleteListing failed", error.code, error.message);
    return { ok: false, error: "Couldn't delete the listing." };
  }
  if (images?.length && r2Configured()) {
    await deleteObjects(images.flatMap((i) => [i.r2_key, i.thumb_key])).catch((e) =>
      console.error("deleteListing: R2 cleanup failed", e),
    );
  }
  expireListingCaches(listing.slug);
  redirect("/admin/listings");
}

