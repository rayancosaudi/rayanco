/** Saves a new photo order; the first photo is the cover. */
export async function reorderListingImages(listingId: string, imageIds: string[]): Promise<ActionResult> {
  const session = await requireUser();
  if (!UUID_RE.test(listingId) || !imageIds.every((i) => UUID_RE.test(i)) || imageIds.length > 60) return NOT_ALLOWED;
  const listing = await getEditableListing(session, listingId);
  if (!listing) return NOT_ALLOWED;

  const results = await Promise.all(
    imageIds.map((imageId, index) =>
      session.supabase
        .from("listing_images")
        .update({ sort_order: index })
        .eq("id", imageId)
        .eq("listing_id", listingId),
    ),
  );
  if (results.some((r) => r.error)) return { ok: false, error: "Couldn't save the photo order." };
  if (isPublicStatus(listing.status)) expireListingCaches(listing.slug);
  return { ok: true };
}

export async function deleteListingImage(listingId: string, imageId: string): Promise<ActionResult> {
  const session = await requireUser();
  if (!UUID_RE.test(listingId) || !UUID_RE.test(imageId)) return NOT_ALLOWED;
  const listing = await getEditableListing(session, listingId);
  if (!listing) return NOT_ALLOWED;
  if (isPublicStatus(listing.status) && (await imageCount(session, listingId)) <= 1) {
    return { ok: false, error: "A published listing needs at least one photo." };
  }

  const { data, error } = await session.supabase
    .from("listing_images")
    .delete()
    .eq("id", imageId)
    .eq("listing_id", listingId)
    .select("r2_key, thumb_key")
    .maybeSingle();
  if (error || !data) return { ok: false, error: "Couldn't delete the photo." };
  if (r2Configured()) {
    await deleteObjects([data.r2_key, data.thumb_key]).catch((e) => console.error("deleteListingImage: R2 cleanup failed", e));
  }
  if (isPublicStatus(listing.status)) expireListingCaches(listing.slug);
  return { ok: true };
}
